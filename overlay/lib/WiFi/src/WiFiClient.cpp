size_t WiFiClient::write(uint8_t b) { return write(&b, 1); }

size_t WiFiClient::write(const uint8_t *buf, size_t size) {
  if (!psock) {
    setWriteError();
    return 0;
  }
  if (size == 0) {
    setWriteError();
    return 0;
  }

  // Wii: IOS socket buffers are small, so a NodeDB dump fills them. No room
  // is a short write (the caller keeps the tail and retries), not a dead link.
  if (!(wii_poll(psock, WII_POLLOUT) & (WII_POLLOUT | WII_POLLERR | WII_POLLHUP)))
    return 0;
  auto ret = wii_write(psock, buf, size);
  if (ret == -1) {
    if (errno)
      errorCode = errno;
    else
      errorCode = ECONNRESET;
    ::printf("WiFiClient: send of %u bytes failed, errno %d\n", (unsigned)size, errorCode);
    return 0; // never (size_t)-1: callers add the result to an offset
  }
  return ret;
}

int WiFiClient::available() {
  if (!psock)
    return 0;
  if (rxpos < rxlen)
    return rxlen - rxpos;
  if (errorCode != 0)
    return 0; // closed or reset: nothing more will come
  if (!(wii_poll(psock, WII_POLLIN) & (WII_POLLIN | WII_POLLERR | WII_POLLHUP)))
    return 0; // nothing waiting: recv would block
  int numread = wii_read(psock, rxbuf, sizeof(rxbuf));
  if (numread > 0) {
    rxpos = 0;
    rxlen = numread;
    return numread;
  }
  if (numread == 0) {
    errorCode = ECONNRESET; // EOF: the client closed
  } else {
    errorCode = errno;
    ::printf("WiFiClient: recv failed, errno %d\n", errorCode);
  }
  return 0;
}

int WiFiClient::read() {
  if (!available())
    return -1;
  return rxbuf[rxpos++];
}

int WiFiClient::read(uint8_t *buf, size_t size) {
  int n = available();
  if (n <= 0)
    return -1;
  if ((size_t)n > size)
    n = (int)size;
  memcpy(buf, rxbuf + rxpos, n);
  rxpos += n;
  return n;
}

int WiFiClient::peek() {
  if (!available())
    return -1;
  return rxbuf[rxpos];
}

void WiFiClient::flush() {
}

void WiFiClient::stop() {
  if (!psock)
    return;

  wii_close(psock);
  psock = 0;
  rxpos = rxlen = 0; // never hand a later connection this one's bytes
}

uint8_t WiFiClient::connected() {

  if (!psock) {
    return 0;
  } else {
    // Arduino semantics: still connected while unread data remains
    return errorCode == 0 || rxpos < rxlen;
  }
}

uint8_t WiFiClient::status() {
  if (!psock) {
    return CLOSED;
  } else {
    return ESTABLISHED;
  }
}

WiFiClient::operator bool() { return connected(); }

IPAddress WiFiClient::remoteIP() const {
    return psock ? IPAddress(peerAddr) : IPAddress(INADDR_NONE);
}

uint16_t WiFiClient::remotePort() const {
    return psock ? peerPort : 0;
}

IPAddress WiFiClient::localIP() const {
    return getAddr(psock, &wii_getsockname);
}

uint16_t WiFiClient::localPort() const {
    return getPort(psock, &wii_getsockname);
}
