namespace {
typedef int(*get_name_f)(int , sockaddr *, socklen_t *);

uint16_t getPort(int fd, const get_name_f getter) {
    if (!fd)
        return 0;
    struct sockaddr_in addr;
    socklen_t len = sizeof(addr);
    if (getter(fd, reinterpret_cast<struct sockaddr*>(&addr), &len) != 0) {
        perror("WiFiClient: Failed to get port");
        return 0;
    }
    return ntohs(addr.sin_port);
}

IPAddress getAddr(int fd, const get_name_f getter) {
    if (!fd)
        return INADDR_NONE;
    struct sockaddr_in addr;
    socklen_t len = sizeof(addr);
    if (getter(fd, reinterpret_cast<struct sockaddr*>(&addr), &len) != 0) {
        perror("WiFiClient: Failed to get IP address");
        return INADDR_NONE;
    }
    return IPAddress(addr.sin_addr.s_addr);
}
}

WiFiClient::WiFiClient(int sock, uint32_t addr, uint16_t port) : psock(sock), peerAddr(addr), peerPort(port) {
  /* Wii: no SIGPIPE */ // SIGPIPE can be generated by a disconnect, we ignore it to avoid a crash.
  if (psock) {
    // Wii: blocking socket, every call gated by a zero-timeout poll. A
    // non-blocking IOS send can queue part of a buffer yet report EAGAIN,
    // which makes the caller resend bytes the client already has.
    int flags = wii_fcntl(psock, F_GETFL, 0);
    wii_fcntl(psock, F_SETFL, flags & ~O_NONBLOCK);
    errorCode = 0;
  }
}

extern "C" int wii_net_up(void);

int WiFiClient::connect(const char *host, uint16_t port) {
  // Wii: Wi-Fi may be off (tcp_api=0); an outgoing client brings it up
  if (!wii_net_up())
    return false;
  stop(); // a reconnect reuses this object

  struct sockaddr_in server;
  memset(&server, 0, sizeof(server));
  server.sin_family = AF_INET;
  server.sin_port = htons(port);
  if (!inet_aton(host, &server.sin_addr)) { // an IP address needs no DNS round trip
    struct hostent *dns = wii_gethostbyname(host);
    if (!dns) {
      ::printf("WiFiClient: Hostname lookup failed %s\n", host);
      return false;
    }
    server.sin_addr = *((struct in_addr *)dns->h_addr);
  }

  // Create socket
  int sock = wii_socket(AF_INET, SOCK_STREAM, 0);
  if (sock == -1) {
    ::printf("WiFiClient: Could not create socket\n");
    return false;
  }

  // Connect to remote server
  if (wii_connect(sock, (struct sockaddr *)&server, sizeof(server)) < 0) {
    ::printf("WiFiClient: connect error\n");
    wii_close(sock);
    return false;
  }

  psock = sock;
  errorCode = 0;
  rxpos = rxlen = 0;
  peerAddr = server.sin_addr.s_addr;
  peerPort = port;

  // Wii: stays blocking, calls are poll-gated (see the constructor)
  return true;
}

